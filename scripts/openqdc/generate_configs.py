"""Write one TopoBench dataset config per OpenQDC dataset.

For every requested dataset a file ``configs/dataset/graph/openqdc_<name>.yaml``
is written. If the dataset is already downloaded (or ``--download`` is given)
the config is filled with detected facts: elements (``atom_types``), number of
energy columns and their names, size, and the true units of the stored
energies and positions (OpenQDC mislabels some, e.g. QM9 and QM7b). Otherwise
the config uses a generic element list and says so in a comment.

Examples
--------
::

    python scripts/openqdc/generate_configs.py                  # all datasets
    python scripts/openqdc/generate_configs.py --datasets QM9 Alchemy --download
"""

import argparse
import json
import sys
from pathlib import Path

from topobench.data.utils.openqdc_utils import (
    FALLBACK_ATOM_TYPES,
    PROJECT_ROOT,
    available_datasets,
    canonical_name,
    default_cache_dir,
    inspect_dataset,
)

CONFIG_DIR = PROJECT_ROOT / "configs" / "dataset" / "graph"
BIG_DATASET = 1_000_000


def config_path(name: str, out_dir: Path = CONFIG_DIR) -> Path:
    """Path of the config file of a dataset."""
    return Path(out_dir) / f"openqdc_{canonical_name(name).lower()}.yaml"


def render(info: dict, energy_method: int = 0) -> str:
    """Render the yaml text of a dataset config from its metadata."""
    name = info["name"]
    cached = info["cached"]
    atom_types = info.get("elements") or FALLBACK_ATOM_TYPES
    total = info.get("energy_kind") != "not_total" and not info.get(
        "not_total"
    )
    stored_e = info.get("stored_energy_unit")
    stored_d = info.get("stored_distance_unit")
    lines = [
        f"# OpenQDC {name} (generated by scripts/openqdc/generate_configs.py;"
    ]
    lines.append("# regenerate instead of editing by hand).")
    if cached:
        lines.append(
            f"# {info['n_molecules']:,} molecules, up to {info['max_atoms']} atoms, "
            f"{info['n_methods']} energy column(s)."
        )
        if info["n_molecules"] > BIG_DATASET:
            lines.append(
                "# Large dataset: set dataset.loader.parameters.max_samples for quick runs."
            )
        if (
            info["declared_energy_unit"] != info.get("stored_energy_unit")
            and total
        ):
            lines.append(
                f"# OpenQDC labels the energies '{info['declared_energy_unit']}' but "
                f"they are {stored_e}; the loader corrects this."
            )
        if info["declared_distance_unit"] != stored_d:
            lines.append(
                f"# OpenQDC labels positions '{info['declared_distance_unit']}' but "
                f"they are {stored_d}; the loader corrects this."
            )
        if not info.get("distance_check_ok", True):
            lines.append(
                "# WARNING: positions fail the bond-length sanity check; verify units."
            )
    else:
        lines.append(
            "# NOT DOWNLOADED when generated: atom_types is a generic element set and"
        )
        lines.append(
            "# units are the declared ones. Run with --download for exact values."
        )
    if info.get("not_total"):
        lines.append(f"# NOTE: not total energies: {info['not_total']}.")
    elif info.get("energy_kind") == "unknown" and cached:
        lines.append(
            "# NOTE: could not confirm these are total energies (unit not verified)."
        )
    if info["has_forces"]:
        lines.append(
            "# Forces exist in OpenQDC but are ignored (energy-only)."
        )
    names = info.get("method_names")
    if names:
        lines.append("# energy_method (column) -> QM method:")
        lines += [f"#   {i}: {n or '(unnamed)'}" for i, n in enumerate(names)]
    elif info["n_methods"]:
        lines.append(
            f"# {info['n_methods']} energy column(s); use energy_method=<index>."
        )

    def yaml_or_null(v):
        return "null" if v is None else v

    baseline = "per_element" if total else "none"
    lines += [
        "",
        "# Dataset loader config",
        "loader:",
        "  _target_: topobench.data.loaders.graph.OpenQDCDatasetLoader",
        "  parameters:",
        "    data_domain: graph",
        "    data_type: openqdc",
        f"    data_name: {name}",
        "    data_dir: ${paths.data_dir}/${dataset.loader.parameters.data_domain}/${dataset.loader.parameters.data_type}",
        "    openqdc_cache_dir: ${oc.env:OPENQDC_CACHE_DIR,${paths.data_dir}/openqdc}",
        f"    atom_types: {json.dumps(atom_types)}",
        "    target: formation_energies # formation_energies | energies | per_atom_formation_energies",
        f"    energy_method: {energy_method}",
        "    energy_unit: ev",
        f"    stored_energy_unit: {yaml_or_null(stored_e)} # true unit of the stored numbers",
        f"    stored_distance_unit: {yaml_or_null(stored_d)}",
        f"    baseline: {baseline} # per_element subtracts fitted per-element energies from y",
        "    edge_method: bonds # bonds (covalent radii) | radius",
        "    bond_scale: 1.3",
        "    cutoff: 5.0 # Angstrom, used when edge_method=radius",
        "    max_samples: null",
        "    subsample_seed: 0",
        "",
        "# Dataset parameters",
        "parameters:",
        "  num_features:",
        f"    - {len(atom_types) + 1} # one-hot over atom_types + formal atomic charge",
        "  num_classes: 1",
        "  task: regression",
        "  loss_type: mse",
        "  monitor_metric: mae",
        "  task_level: graph",
        "  max_dim_if_lifted: 3",
        "  preserve_edge_attr_if_lifted: False",
        "",
        "# splits",
        "split_params:",
        "  learning_setting: inductive",
        "  data_split_dir: ${paths.data_dir}/data_splits/${dataset.loader.parameters.data_name}_m${dataset.loader.parameters.energy_method}_n${dataset.loader.parameters.max_samples}_s${dataset.loader.parameters.subsample_seed}",
        "  data_seed: 0",
        "  split_type: random",
        "  k: 10",
        "  train_prop: 0.8",
        "",
        "# Dataloader parameters",
        "dataloader_params:",
        "  batch_size: 128",
        "  num_workers: 0",
        "  pin_memory: False",
        "",
    ]
    return "\n".join(lines)


def write_config(
    name: str,
    cache_dir: str,
    download: bool = False,
    out_dir: Path = CONFIG_DIR,
    energy_method: int = 0,
) -> tuple[Path | None, dict]:
    """Inspect a dataset and write its config.

    Returns
    -------
    tuple
        ``(path or None if the dataset is unusable, metadata)``.
    """
    info = inspect_dataset(name, cache_dir, download, energy_method)
    if info.get("unusable"):
        return None, info
    path = config_path(name, out_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(info, energy_method))
    return path, info


def ensure_config(
    name: str, cache_dir: str, regenerate: bool = False, **kwargs
) -> Path:
    """Return the config of a dataset, creating it (with download) if missing.

    A config written without data (generic atom types) is regenerated once the
    dataset is needed, so training always runs on detected elements and units.
    """
    path = config_path(name)
    stale = path.exists() and "NOT DOWNLOADED" in path.read_text()
    if regenerate or stale or not path.exists():
        path, info = write_config(name, cache_dir, download=True, **kwargs)
        if path is None:
            raise RuntimeError(
                f"{canonical_name(name)} is unusable: {info['unusable']}."
            )
    return path


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--datasets", nargs="+", help="default: all")
    p.add_argument("--cache-dir", default=default_cache_dir())
    p.add_argument("--out-dir", default=str(CONFIG_DIR))
    p.add_argument(
        "--download",
        action="store_true",
        help="download missing datasets to detect elements/units "
        "(needs --datasets: some datasets are hundreds of GB)",
    )
    p.add_argument("--report", help="write the collected metadata as json")
    args = p.parse_args()
    if args.download and not args.datasets:
        sys.exit("--download needs an explicit --datasets list.")

    names = (
        [canonical_name(n) for n in args.datasets]
        if args.datasets
        else sorted(available_datasets())
    )
    report = {}
    for name in names:
        path, info = write_config(
            name, args.cache_dir, args.download, Path(args.out_dir)
        )
        report[name] = info
        if path is None:
            print(f"{name:18s} SKIPPED: {info['unusable']}")
            continue
        status = "detected" if info["cached"] else "generic (not downloaded)"
        flags = []
        if info["cached"]:
            if info["declared_energy_unit"] != info["stored_energy_unit"]:
                flags.append(f"energy unit {info['stored_energy_unit']}")
            if info["declared_distance_unit"] != info["stored_distance_unit"]:
                flags.append(f"distance unit {info['stored_distance_unit']}")
            if info["energy_kind"] != "total":
                flags.append(f"energy_kind={info['energy_kind']}")
        print(f"{name:18s} {status:26s} {' | '.join(flags)} -> {path.name}")
    if args.report:
        Path(args.report).write_text(json.dumps(report, indent=2, default=str))


if __name__ == "__main__":
    main()
