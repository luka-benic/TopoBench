"""Write one TopoBench dataset config per OpenQDC dataset.

For every requested dataset a file ``configs/dataset/graph/openqdc_<name>.yaml``
is written. If the dataset is already downloaded (or ``--download`` is given)
the config is filled with detected facts: elements (``atom_types``), number of
energy columns and their names, and size. Otherwise the config uses a generic
element list and says so in a comment. Energies (eV) and positions (Angstrom)
always come from OpenQDC's own unit conversion.

Examples
--------
::

    python scripts/openqdc/generate_configs.py                  # the default list
    python scripts/openqdc/generate_configs.py --datasets QM9 --energy-method 3
    python scripts/openqdc/generate_configs.py --datasets VQM24 --download
    python scripts/openqdc/generate_configs.py --all            # every dataset
"""

import argparse
import json
import os
from pathlib import Path

import yaml

from topobench.data.utils.openqdc_utils import (
    FALLBACK_ATOM_TYPES,
    PROJECT_ROOT,
    UNUSABLE,
    available_datasets,
    canonical_name,
    default_cache_dir,
    inspect_dataset,
    locked,
    resolve_energy_method,
)

CONFIG_DIR = PROJECT_ROOT / "configs" / "dataset" / "graph"
BIG_DATASET = 1_000_000
# Datasets configured by default (use --all for every OpenQDC dataset).
DEFAULT_DATASETS = [
    "QM9",
    "MultixcQM9",
    "QM7",
    "QM7b",
    "Alchemy",
    "VQM24",
    "TMQM",
]


def config_path(name: str, out_dir: Path = CONFIG_DIR) -> Path:
    """Path of the config file of a dataset."""
    return Path(out_dir) / f"openqdc_{canonical_name(name).lower()}.yaml"


def configured_loader_parameter(
    name: str, key: str, out_dir: Path = CONFIG_DIR
):
    """Read a ``loader.parameters`` value from the yaml of a dataset.

    Parameters
    ----------
    name : str
        Dataset name.
    key : str
        Parameter name.
    out_dir : Path
        Directory of the dataset configs.

    Returns
    -------
    Any
        The value, or None if the dataset has no config yet or the config
        does not set it.
    """
    path = config_path(name, out_dir)
    if not path.exists():
        return None
    cfg = yaml.safe_load(path.read_text())
    return cfg["loader"]["parameters"].get(key)


def configured_energy_method(name: str, out_dir: Path = CONFIG_DIR):
    """Read the energy column chosen in the yaml of a dataset.

    Parameters
    ----------
    name : str
        Dataset name.
    out_dir : Path
        Directory of the dataset configs.

    Returns
    -------
    int or str or None
        The ``loader.parameters.energy_method`` value, or None if the dataset
        has no config yet.
    """
    path = config_path(name, out_dir)
    if not path.exists():
        return None
    cfg = yaml.safe_load(path.read_text())
    return cfg["loader"]["parameters"].get("energy_method")


def render(info: dict, energy_method: int = 0) -> str:
    """Render the yaml text of a dataset config from its metadata."""
    name = info["name"]
    cached = info["cached"]
    atom_types = info.get("elements") or FALLBACK_ATOM_TYPES
    lines = [
        f"# OpenQDC {name} (generated by scripts/openqdc/generate_configs.py;"
    ]
    lines.append("# regenerate instead of editing by hand).")
    if cached:
        lines.append(
            f"# {info['n_molecules']:,} molecules, up to {info['max_atoms']} atoms, "
            f"{info['n_methods']} energy column(s)."
        )
        if info["n_molecules"] > BIG_DATASET:
            lines.append(
                "# Large dataset: set dataset.loader.parameters.max_samples for quick runs."
            )
    elif info.get("unusable"):
        lines.append(f"# UNUSABLE: {info['unusable']}.")
        lines.append(
            "# Placeholder only: atom_types is generic and training stops with an error."
        )
    else:
        lines.append(
            "# NOT DOWNLOADED when generated: atom_types is a generic element set and"
        )
        lines.append("# Run with --download for the exact elements.")
    if info.get("not_total"):
        lines.append(f"# NOTE: not total energies: {info['not_total']}.")
    names = info.get("method_names") or []
    lines.append(
        f"# Energy columns ({len(names)}): set loader.parameters.energy_method to the index"
    )
    lines.append("# of the column to train on.")
    lines += [f"#   {i}: {n or '(unnamed)'}" for i, n in enumerate(names)]

    baseline = (
        "none"  # per_element subtracts a fitted baseline (train split only)
    )
    lines += [
        "",
        "# Dataset loader config",
        "loader:",
        "  _target_: topobench.data.loaders.graph.OpenQDCDatasetLoader",
        "  parameters:",
        "    data_domain: graph",
        "    data_type: openqdc",
        f"    data_name: {name}",
        "    data_dir: ${paths.data_dir}/${dataset.loader.parameters.data_domain}/${dataset.loader.parameters.data_type}",
        "    openqdc_cache_dir: ${oc.env:OPENQDC_CACHE_DIR,${paths.data_dir}/openqdc}",
        f"    atom_types: {json.dumps(atom_types)}",
        "    target: energies # energies (total) | formation_energies | per_atom_formation_energies",
        "    # Energy column to train on: its index in the list at the top of this file.",
        "    # Command line: dataset.loader.parameters.energy_method=<index>"
        " or --energy-method <index or name> in the scripts.",
        f"    energy_method: {energy_method}",
        f"    baseline: {baseline} # none (raw energy) | per_element (subtract per-element energies fitted on the train split)",
        "    edge_method: bonds # bonds (covalent radii) | radius",
        "    bond_scale: 1.3",
        "    cutoff: 5.0 # Angstrom, used when edge_method=radius",
        "    max_samples: null",
        "    subsample_seed: 0",
        "    # Train/valid/test split by OpenQDC index; the MACE scripts use the same one.",
        "    valid_fraction: 0.1",
        "    test_fraction: 0.1",
        "    split_seed: 0",
        "",
        "# Dataset parameters",
        "parameters:",
        "  num_features:",
        f"    - {len(atom_types) + 1} # one-hot over atom_types + formal atomic charge",
        "  num_classes: 1",
        "  task: regression",
        "  loss_type: mse",
        "  monitor_metric: mae",
        "  task_level: graph",
        "  max_dim_if_lifted: 3",
        "  preserve_edge_attr_if_lifted: False",
        "",
        "# splits",
        "split_params:",
        "  learning_setting: inductive",
        "  split_type: fixed # the dataset provides the split (loader.parameters.split_seed)",
        "",
        "# Dataloader parameters",
        "dataloader_params:",
        "  batch_size: 128",
        "  num_workers: 0",
        "  pin_memory: False",
        "",
    ]
    return "\n".join(lines)


def write_config(
    name: str,
    cache_dir: str,
    download: bool = False,
    out_dir: Path = CONFIG_DIR,
    energy_method=None,
) -> tuple[Path, dict]:
    """Inspect a dataset and write its config.

    Parameters
    ----------
    energy_method : int or str, optional
        Energy column (index or name). None keeps the column already chosen in
        the existing yaml, or 0 for a new one.

    Returns
    -------
    tuple
        ``(path, metadata)``.
    """
    info = inspect_dataset(name, cache_dir, download)
    if energy_method is None:
        energy_method = configured_energy_method(name, out_dir)
    energy_method = resolve_energy_method(
        info["method_names"], 0 if energy_method is None else energy_method
    )
    path = config_path(name, out_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    # Write to a temporary file and rename it, so a reader never sees a
    # half-written yaml.
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(render(info, energy_method))
    os.replace(tmp, path)
    return path, info


def ensure_config(
    name: str, cache_dir: str, regenerate: bool = False, **kwargs
) -> Path:
    """Return the config of a dataset, creating it (with download) if missing.

    A config written without data (generic atom types) is regenerated once the
    dataset is needed, so training always runs on the detected elements. The
    energy column chosen in an existing yaml is kept.
    """
    if canonical_name(name) in UNUSABLE:
        raise RuntimeError(
            f"{canonical_name(name)} is unusable: {UNUSABLE[canonical_name(name)]}."
        )
    path = config_path(name)
    Path(cache_dir).mkdir(parents=True, exist_ok=True)
    # One process at a time writes a config; the others wait and then see it.
    lock = Path(cache_dir) / f".{canonical_name(name)}.config.lock"
    with locked(str(lock), f"{canonical_name(name)} config"):
        stale = path.exists() and "NOT DOWNLOADED" in path.read_text()
        if regenerate or stale or not path.exists():
            path, _ = write_config(name, cache_dir, download=True, **kwargs)
    return path


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument(
        "--datasets",
        nargs="+",
        help=f"default: {' '.join(DEFAULT_DATASETS)}",
    )
    p.add_argument("--all", action="store_true", help="every OpenQDC dataset")
    p.add_argument(
        "--energy-method",
        default=None,
        help="energy column (index or name) written into the yaml; default: "
        "keep the one already in the yaml, else 0",
    )
    p.add_argument("--cache-dir", default=default_cache_dir())
    p.add_argument("--out-dir", default=str(CONFIG_DIR))
    p.add_argument(
        "--download",
        action="store_true",
        help="download missing datasets to detect their elements "
        "(needs --datasets: some datasets are hundreds of GB)",
    )
    p.add_argument("--report", help="write the collected metadata as json")
    args = p.parse_args()
    if args.download and args.all:
        p.error("--download needs an explicit --datasets list, not --all.")
    if args.all:
        names = sorted(available_datasets())
    else:
        names = [canonical_name(n) for n in args.datasets or DEFAULT_DATASETS]
    report = {}
    for name in names:
        path, info = write_config(
            name,
            args.cache_dir,
            args.download,
            Path(args.out_dir),
            args.energy_method,
        )
        report[name] = info
        status = "detected" if info["cached"] else "generic (not downloaded)"
        if info["unusable"]:
            status = "UNUSABLE placeholder"
        note = (
            f"not total energies: {info['not_total']}"
            if info["not_total"]
            else ""
        )
        column = configured_energy_method(name, Path(args.out_dir))
        print(
            f"{name:12s} {status:26s} column {column}: "
            f"{info['method_names'][column]!r} {note} -> {path.name}"
        )
    if args.report:
        Path(args.report).write_text(json.dumps(report, indent=2, default=str))


if __name__ == "__main__":
    main()
